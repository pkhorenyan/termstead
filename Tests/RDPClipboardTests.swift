import AppKit
import Foundation
import Testing
@testable import Termstead

struct RDPClipboardTextTests {
    @Test func lineEndingsChangeOnTheWay() {
        #expect(RDPDesktop.serverText("one\ntwo\r\nthree") == "one\r\ntwo\r\nthree")
        #expect(RDPDesktop.macText("one\r\ntwo") == "one\ntwo")
    }

    @Test func markedContentStaysOrWaitsForAPaste() {
        let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        let generated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        #expect(RDPDesktop.mayShare([.string], onPaste: false))
        #expect(!RDPDesktop.mayShare([.string, concealed], onPaste: false))
        #expect(RDPDesktop.mayShare([.string, concealed], onPaste: true))
        #expect(!RDPDesktop.mayShare([.string, transient], onPaste: true))
        #expect(!RDPDesktop.mayShare([.string, generated], onPaste: true))
    }
}

/// Text copied on either side reaches the other, against the lab's xrdp —
/// its clipboard read and set with xclip in the container. The Mac's side
/// is a private pasteboard, never the user's.
@MainActor
@Suite(.serialized, .enabled(if: TestLabRDP.isUp && TestLabRDP.docker != nil,
                             "the lab's RDP server is not running (TestLab/lab.sh up)"))
struct RDPClipboardTests {
    private func wait(upTo seconds: Double, until done: () -> Bool) async {
        let deadline = Date().addingTimeInterval(seconds)
        while !done(), Date() < deadline {
            try? await Task.sleep(for: .milliseconds(100))
        }
    }

    /// The X display of the lab user's session: its X server runs as them.
    private func display() throws -> String {
        let found = TestLabRDP.inContainer(["sh", "-c", "ps -u lab -o args= | grep -o 'Xorg :[0-9]*' | head -1"])
        let display = try #require(found.output.split(separator: " ").last.map(String.init))
        return display.trimmingCharacters(in: .whitespacesAndNewlines)
    }

    /// `xclip` as the lab user, in their session.
    private func xclip(_ arguments: String) throws -> (status: Int32, output: String) {
        TestLabRDP.inContainer(["su", "lab", "-c",
                                "DISPLAY=\(try display()) timeout 5 xclip -selection clipboard \(arguments)"])
    }

    private func open(pasteboard: NSPasteboard, keyboard: @escaping () -> Bool = { true }) async throws -> RDPDesktop {
        let desktop = RDPDesktop()
        desktop.knownHosts = TestLabRDP.knownHosts
        desktop.pasteboard = pasteboard
        desktop.hasKeyboard = keyboard
        desktop.availableSize = { (CGSize(width: 800, height: 600), 1) }
        var launch = RDPLaunch(session: SessionStore.sample().session("lab-rdp")!, password: "lab")
        launch.options.sound = false
        desktop.start(launch) { try await RDPSocket.connect(host: "127.0.0.1", port: 3390) }
        await TestLabRDP.waitUntilShowing(desktop)
        try #require(desktop.phase == .showing)
        return desktop
    }

    @Test func textCopiedHereCanBePastedThere() async throws {
        let pasteboard = NSPasteboard(name: .init("termstead-test-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        let text = "from the Mac \(Int.random(in: 1000...9999)) — ✓"
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)

        let desktop = try await open(pasteboard: pasteboard)
        var pasted = ""
        for _ in 0..<20 where pasted != text {
            try await Task.sleep(for: .milliseconds(500))
            pasted = try xclip("-o").output
        }
        #expect(pasted == text)
        desktop.stop()
    }

    /// What the server's clipboard holds now, as its user would paste it.
    private func serverText(expecting text: String, for seconds: Int) async throws -> String {
        var pasted = ""
        for _ in 0..<(seconds * 2) where pasted != text {
            try await Task.sleep(for: .milliseconds(500))
            pasted = try xclip("-o").output
        }
        return pasted
    }

    /// A desktop without the keyboard sees nothing copied meanwhile; the
    /// keyboard coming back brings the text with it.
    @Test func onlyTheDesktopWithTheKeyboardGetsTheText() async throws {
        let pasteboard = NSPasteboard(name: .init("termstead-test-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        var keyboard = false
        let desktop = try await open(pasteboard: pasteboard, keyboard: { keyboard })
        let text = "copied elsewhere \(Int.random(in: 1000...9999))"
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        #expect(try await serverText(expecting: text, for: 3) != text)

        keyboard = true
        desktop.keyboardArrived()
        #expect(try await serverText(expecting: text, for: 5) == text)
        desktop.stop()
    }

    /// A password manager's copy goes over on ⌘V only. Without the keys
    /// ⌘V presses: they land in whatever has the focus in the lab user's
    /// desktop, which outlives the test (a Ctrl+V once left Thunar showing
    /// an error there).
    @Test func aConcealedCopyWaitsForPaste() async throws {
        let pasteboard = NSPasteboard(name: .init("termstead-test-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        let desktop = try await open(pasteboard: pasteboard)
        let secret = "secret \(Int.random(in: 1000...9999))"
        pasteboard.clearContents()
        pasteboard.setString(secret, forType: .string)
        pasteboard.setData(Data(), forType: .init("org.nspasteboard.ConcealedType"))
        #expect(try await serverText(expecting: secret, for: 3) != secret)

        desktop.offerForPaste()
        #expect(try await serverText(expecting: secret, for: 5) == secret)
        desktop.stop()
    }

    @Test func textCopiedThereComesHere() async throws {
        let pasteboard = NSPasteboard(name: .init("termstead-test-\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        pasteboard.clearContents()
        let desktop = try await open(pasteboard: pasteboard)
        try await Task.sleep(for: .seconds(1))

        let text = "from xrdp \(Int.random(in: 1000...9999))"
        // xclip serves the selection in the background; one paste, then it goes.
        _ = TestLabRDP.inContainer(["su", "lab", "-c",
                                    "printf '%s' '\(text)' | DISPLAY=\(try display()) xclip -selection clipboard -l 1 &"])
        await wait(upTo: 10) { pasteboard.string(forType: .string) == text }
        #expect(pasteboard.string(forType: .string) == text)
        desktop.stop()
    }
}
